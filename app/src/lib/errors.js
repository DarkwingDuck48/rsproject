/**
 * @fileoverview Различение «штатных» ошибок бэкенда от реальных.
 *
 * Бэкенд возвращает ошибки строками (Result<_, String>), поэтому фронтенд
 * вынужден сравнивать тексты. Это хрупкий контракт, но пока он есть —
 * держим список в одном месте, чтобы не рассылать магические строки по вьюхам.
 */

/** Сообщения об ошибках, означающие «проект сейчас не выбран» (штатная ситуация). */
export const NO_PROJECT_ERRORS = ["Не выбран проект", "Проект не найден"];

/**
 * @param {unknown} err - Ошибка из invoke() (обычно string).
 * @returns {boolean} true, если ошибка = «проект не выбран» (не надо пугать пользователя).
 */
export function isNoProjectError(err) {
  return typeof err === "string" && NO_PROJECT_ERRORS.includes(err);
}
